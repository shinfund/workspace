const COMBINE_GUBUN = new Set(['기타','태양광발전설비']);

function norm(s){
  return String(s||'')
    .replace(/^ㅇ\s*/, '')
    .replace(/\s+/g, '')
    .replace(/내역/g, '내력'); // known typo in original field template vs catalog
}

const catalogIndex = new Map();
REPORT_CHECKLIST_ORDER.forEach(item=>{
  const key = norm(item.구분) + '|' + norm(COMBINE_GUBUN.has(item.구분)?'':(item.설비명||'')) + '|' + norm(item.점검내용);
  catalogIndex.set(key, item);
});

const wb = new ExcelJS.Workbook();
await wb.xlsx.readFile(filePath);

function cellText(cell){
  let v = cell.value;
  if (v && typeof v === 'object') {
    if (v instanceof Date) return v;
    if (v.result !== undefined) v = v.result;
    else if (v.richText) v = v.richText.map(t=>t.text).join('');
  }
  return v;
}

const matched = [];
const unmatched = [];

for (const sheetName of ['월간점검표1','월간점검표2','월간점검표3']) {
  const ws = wb.getWorksheet(sheetName);
  for (let r = 6; r <= ws.rowCount; r++) {
    const row = ws.getRow(r);
    const 구분 = cellText(row.getCell(1));
    const 설비명raw = cellText(row.getCell(2));
    const 점검내용 = cellText(row.getCell(3));
    const 점검결과 = cellText(row.getCell(4));
    const 점검일자 = cellText(row.getCell(5));
    const 비고 = cellText(row.getCell(6));
    if (!구분 && !점검내용) continue;

    const key = norm(구분) + '|' + norm(COMBINE_GUBUN.has(구분)?'':(설비명raw||'')) + '|' + norm(점검내용);
    const cat = catalogIndex.get(key);
    if (!cat) {
      unmatched.push({sheet: sheetName, row: r, 구분, 설비명: 설비명raw, 점검내용, 점검결과, 점검일자, 비고});
      continue;
    }
    // Skip periodic items not performed this month (dash / no date)
    const hasDate = 점검일자 instanceof Date;
    if (!hasDate) continue;

    matched.push({
      sheet: sheetName, row: r,
      터널명: TUNNEL,
      구분: cat.구분,
      설비명: cat.설비명, // null for 기타/태양광발전설비, catalog text otherwise
      점검내용: cat.점검내용,
      점검결과: 점검결과 || '',
      점검일자: 점검일자.toISOString().slice(0,10),
      비고: 비고 || '',
      제목: `${TUNNEL} 월간점검결과표`
    });
  }
}

